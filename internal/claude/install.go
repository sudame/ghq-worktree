package claude

import (
	_ "embed"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

//go:embed SKILL.md
var skillTemplate string

var headerRe = regexp.MustCompile(`generated by ghq-worktree (\S+)\.`)

func skillPath(dir string) string {
	return filepath.Join(dir, "skills", "ghq-worktree", "SKILL.md")
}

// Skill は version で生成したスキルの中身を返す。
func Skill(version string) string {
	header := fmt.Sprintf("<!-- generated by ghq-worktree %s. Do not edit; run `ghq-worktree install claude-code` again instead. -->", version)
	return strings.Replace(skillTemplate, "{{HEADER}}", header, 1)
}

// Install はフックとスキルを Claude Code の設定ディレクトリ dir に書き込む。
func Install(dir, version string) error {
	if err := updateSettings(dir, true); err != nil {
		return err
	}
	return writeFile(skillPath(dir), []byte(Skill(version)))
}

// Uninstall は Install が書き込んだものを消す。
func Uninstall(dir string) error {
	if err := updateSettings(dir, false); err != nil {
		return err
	}
	p := skillPath(dir)
	if err := os.Remove(p); err != nil && !os.IsNotExist(err) {
		return err
	}
	if err := os.Remove(filepath.Dir(p)); err != nil && !os.IsNotExist(err) {
		return err
	}
	return nil
}

// InstalledSkillVersion は入っているスキルを生成したバージョンを返す。入っていなければ空文字。
func InstalledSkillVersion(dir string) string {
	data, err := os.ReadFile(skillPath(dir))
	if err != nil {
		return ""
	}
	if m := headerRe.FindSubmatch(data); m != nil {
		return string(m[1])
	}
	return ""
}
